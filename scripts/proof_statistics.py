#!/usr/bin/env python3
"""Proof statistics of a `domino easycrypt prove` output directory, as Markdown tables.

    scripts/proof_statistics.py <out>/<Theorem> [--before <git-ref>] [-o FILE]

<out>/<Theorem> is the directory that `domino easycrypt prove --out <out>` writes (for example
`~/ec4whs/autogenerated/Full4WHS`). The script reads only these files of it:

  session/<job>/<O>.record.json   the admits of each oracle (node, claim, reason) and its status
  progress/<job>/report.txt       goals closed, lockstep and EasyCrypt time, time by role and smt
                                  calls of each oracle; the job's wall time on the last line
  <job>_<O>.ec                    the key case splits (`case (…) => [->|?].`) of each oracle
  Comp_<C>.ec                     the number of game invariants of composition C (`op GameInv_…`)

A job is an equivalence `Eq_<L>_<R>` (a hop) or a side-invariant job `SideInv_<C>`.

With `--before REF` the same files are also read at the git commit REF of the repository that holds
the directory, and the tables show the old numbers beside the new ones ("now (before)").

The output holds only numbers. The analysis (why an admit stays, what to try next) is written by
hand. Peak memory is not in any of the files; measure it with `/usr/bin/time -v`.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone

ROLES = ["quick close", "structure", "exit path", "reduce", "split", "part fallback",
         "side-goal fallback", "admit"]
GOAL_TYPES = ["equal-output", "invariant conjunct", "branch-condition", "side-goal", "other"]
CASE_SENTENCE = re.compile(r"^(\s*)(\+ )?case \(.*\) => \[->\|\?\]\.\s*$")


# ---------------------------------------------------------------------------------------------
# Sources: the working tree, or the files of a git commit
# ---------------------------------------------------------------------------------------------

class Tree:
    """The files of the output directory, on disk (ref None) or at a git commit."""

    def __init__(self, root, ref=None):
        self.root, self.ref = root, ref
        if ref is None:
            self.files = set()
            for sub in ("session", "progress"):
                for dirpath, _, names in os.walk(os.path.join(root, sub)):
                    for n in names:
                        self.files.add(os.path.relpath(os.path.join(dirpath, n), root))
            self.files |= {n for n in os.listdir(root) if n.endswith(".ec")}
        else:
            out = git(root, "ls-tree", "-r", "--name-only", ref, "--", ".")
            self.files = set(out.splitlines())

    def read(self, rel):
        if rel not in self.files:
            return None
        if self.ref is None:
            with open(os.path.join(self.root, rel), encoding="utf-8") as f:
                return f.read()
        return git(self.root, "show", f"{self.ref}:./{rel}")


def git(cwd, *args):
    return subprocess.run(["git", "-C", cwd, *args], check=True, capture_output=True,
                          text=True).stdout


# ---------------------------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------------------------

def seconds(text):
    """'1m 22s' / '0.7s' / '1h 2m' -> seconds."""
    unit = {"h": 3600, "m": 60, "s": 1}
    return sum(float(v) * unit[u] for v, u in re.findall(r"([\d.]+)\s*([hms])", text))


ORACLE_HEAD = re.compile(r"^  (\w+): lockstep (\d+) joint paths, (\d+) nodes, (\d+) stuck points \(([^)]*)\)")
GOALS = re.compile(r"goals closed: (\d+), (?:no admit|(\d+) admits(?: \(([^)]*)\))?), "
                   r"fallbacks: (\d+), EasyCrypt time ([^ ]+) \((\d+) attempts undone\)")
ROLE = re.compile(r"^\s{6}(" + "|".join(map(re.escape, ROLES)) + r")\s+(\d+)\s+((?:[\d.]+[hms]\s?)+?)\s+(\d+)\s+([\d.]+ (?:B|kB|MB|GB))\s*$")
EC = re.compile(r"EasyCrypt: tactic ([^(]+)\(smt ([^:]+): translate ([^,]+), prepare ([^,]+), "
                r"prover ([^;]+);\s+(\d+) calls: (\d+) valid, (\d+) timeout, (\d+) unknown\), "
                r"serialize ([^,]+), Domino parse (\S+)")
TOTAL = re.compile(r"^(\d+) oracles, (\d+) goals closed, (?:no admit|(\d+) admits), ([\d.]+)s", re.M)
HEADER = re.compile(r"^tactics for (\S+)\.ec \((?:proofstep (\d+): (.*)|side invariants of (\w+))\)", re.M)


def parse_report(text):
    """progress/<job>/report.txt -> (header info, {oracle: stats}, wall seconds)."""
    oracles, cur = {}, None
    for line in text.splitlines():
        m = ORACLE_HEAD.match(line)
        if m:
            cur = {"lockstep": seconds(m.group(5)), "roles": {}, "ec": 0.0, "goals": 0}
            oracles[m.group(1)] = cur
            continue
        if cur is None:
            continue
        if m := GOALS.search(line):
            cur["goals"] = int(m.group(1))
            cur["ec"] = seconds(m.group(5))
        elif m := ROLE.match(line):
            cur["roles"][m.group(1)] = (int(m.group(2)), seconds(m.group(3)), int(m.group(4)))
    for name, block in re.findall(r"^  (\w+): lockstep.*?\n(.*?)(?=^  \w+: lockstep|\Z)", text, re.M | re.S):
        if m := EC.search(block):
            g = m.groups()
            oracles[name].update(tactic=seconds(g[0]), smt=seconds(g[1]), translate=seconds(g[2]),
                                 prepare=seconds(g[3]), prover=seconds(g[4]),
                                 calls=(int(g[6]), int(g[7]), int(g[8])),
                                 serialize=seconds(g[9]), parse=seconds(g[10]))
    total = TOTAL.search(text)
    return oracles, (float(total.group(4)) if total else None)


def case_splits(ec_text):
    """(split parts, case sentences, split parts with an admitted case) of an oracle's .ec file.

    Each `case (…) => [->|?].` makes one more case, so a part with s case sentences has s + 1
    cases. The bullets of a sentence start in the column of its text. A case sentence on a bullet
    (`+ case …`) is nested when the nearest line above it that is not inside a sibling bullet is
    a case sentence whose text starts in the bullet's column; any other case sentence starts a
    split part. The admitted cases of a part (`admit. (* domino: … (case …) … *)`) come after its
    first case sentence and before the next part's."""
    lines = (ec_text or "").splitlines()
    parts = sentences = with_admit = 0
    marked = False
    for i, line in enumerate(lines):
        if "admit. (* domino:" in line and "(case " in line and parts and not marked:
            with_admit, marked = with_admit + 1, True
        m = CASE_SENTENCE.match(line)
        if not m:
            continue
        sentences += 1
        if starts_part(lines, i, m):
            parts, marked = parts + 1, False
    return parts, sentences, with_admit


def starts_part(lines, i, m):
    if m.group(2) is None:
        return True
    col = len(m.group(1))
    for above in reversed(lines[:i]):
        indent = len(above) - len(above.lstrip())
        if not above.strip() or indent > col or (indent == col and above.lstrip().startswith("+ ")):
            continue
        text_col = indent + 2 * above.lstrip().startswith("+ ")
        return not (text_col == col and CASE_SENTENCE.match(above))
    return True


def goal_type(claim):
    claim = claim or ""
    if claim.startswith("invariant/"):
        return "invariant conjunct"
    if claim.startswith("equal-output"):
        return "equal-output"
    if claim in ("branch-condition", "side-goal"):
        return claim
    return "other"


def predicate(claim):
    """'invariant/GameInv_kmac__is__wellformed_of_H6 (case …)' -> 'kmac_is_wellformed'."""
    name = re.sub(r" \(case .*", "", claim.removeprefix("invariant/"))
    if m := re.fullmatch(r"GameInv_(.*)_of_\w+", name):
        name = m.group(1).replace("__", "_")
    return name


def load(tree):
    """All jobs of the tree: {job: Job dict}, hops ordered by proofstep, then side invariants."""
    jobs = {}
    for rel in sorted(tree.files):
        m = re.fullmatch(r"progress/((?:Eq|SideInv)_\w+)/report\.txt", rel)
        if not m:
            continue
        job, text = m.group(1), tree.read(rel)
        head = HEADER.search(text)
        oracles, wall = parse_report(text)
        side = job.startswith("SideInv_")
        info = {"name": job, "side": side, "oracles": oracles, "wall": wall,
                "proofstep": int(head.group(2)) if head and head.group(2) else None,
                "title": (head.group(4) if side else head.group(3)) if head else job,
                "updated": None, "admits": {}}
        for o in oracles:
            rec = tree.read(f"session/{job}/{o}.record.json")
            if rec:
                d = json.loads(rec)
                info["updated"] = max(filter(None, [info["updated"], d.get("updated")]))
                info["admits"][o] = [a for orc in d["oracles"] for a in orc.get("admits", [])]
            oracles[o]["splits"] = case_splits(tree.read(f"{job}_{o}.ec"))
        if side:
            comp = tree.read(f"Comp_{info['title']}.ec") or ""
            info["game_invariants"] = len(re.findall(r"^op GameInv_", comp, re.M))
        jobs[job] = info
    order = sorted(jobs.values(), key=lambda j: (j["side"], j["proofstep"] if j["proofstep"] is not None else 1e9, j["name"]))
    return {j["name"]: j for j in order}


# ---------------------------------------------------------------------------------------------
# Numbers of a job
# ---------------------------------------------------------------------------------------------

def admits_of(job):
    return [a for o in job["oracles"] for a in job["admits"].get(o, [])]


def total(job, key):
    return sum(o.get(key, 0) for o in job["oracles"].values())


def work(job):
    return total(job, "lockstep") + total(job, "ec")


def slowest(job):
    name, o = max(job["oracles"].items(), key=lambda kv: kv[1]["lockstep"] + kv[1]["ec"])
    return f"{name} {dur(o['lockstep'] + o['ec'], short=True)}"


def cases(job):
    """(split parts, cases, admitted cases, split parts with an admitted case) of a job."""
    parts, sentences, with_admit = (sum(o["splits"][k] for o in job["oracles"].values()) for k in range(3))
    admitted = sum(1 for a in admits_of(job) if "(case " in (a.get("claim") or ""))
    return parts, sentences + parts, admitted, with_admit


# ---------------------------------------------------------------------------------------------
# Formatting
# ---------------------------------------------------------------------------------------------

def num(x):
    return f"{x:,.0f}"


def dur(s, short=False):
    if s is None:
        return "—"
    text = f"{s:,.0f} s" if s >= 10 else f"{s:.1f} s"
    if short or s < 60:
        return text
    if s < 3600:
        m = s / 60
        return f"{text} ({m:.1f} m)" if m < 10 else f"{text} ({m:.0f} m)"
    return f"{text} ({s / 3600:.1f} h)"


def with_before(now, before, fmt=str):
    if before is None:
        return fmt(now)
    return f"{fmt(now)} ({fmt(before)})"


def change(now, before):
    d = now - before
    return "=" if d == 0 else f"{d:+,}".replace("-", "−")


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def blank0(x):
    return "" if x == 0 else x


# ---------------------------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------------------------

def section(jobs, before, side):
    """All tables of the hops (side False) or of the side invariants (side True)."""
    sel = [j for j in jobs.values() if j["side"] == side]
    if not sel:
        return []
    old = lambda j: before.get(j["name"]) if before else None
    label = "Composition" if side else "Hop"
    out = []

    # Summary
    head = [label] + (["Game invariants"] if side else ["Proofstep"]) + ["Goals closed", "Admits"]
    if before:
        head += ["Admits before", "Change"]
    head += ["Wall", "Work (Σ oracles)", "Slowest oracle"]
    if before:
        head += ["Wall before", "Work before"]
    rows, tot = [], Counter()
    for j in sel:
        n, b = len(admits_of(j)), old(j)
        r = [j["title"], j.get("game_invariants") if side else j["proofstep"], num(total(j, "goals")), f"**{n}**"]
        if before:
            r += [len(admits_of(b)) if b else "—", change(n, len(admits_of(b))) if b else "—"]
        r += [dur(j["wall"]), dur(work(j)), slowest(j)]
        if before:
            r += [dur(b["wall"]) if b else "—", dur(work(b)) if b else "—"]
        rows.append(r)
        tot.update(goals=total(j, "goals"), admits=n, wall=j["wall"] or 0, work=work(j))
        if b:
            tot.update(b_admits=len(admits_of(b)), b_wall=b["wall"] or 0, b_work=work(b))
    r = ["**Total**", "", f"**{num(tot['goals'])}**", f"**{tot['admits']}**"]
    if before:
        r += [f"**{tot['b_admits']}**", f"**{change(tot['admits'], tot['b_admits'])}**"]
    r += [f"**{dur(tot['wall'])}**", f"**{dur(tot['work'])}**", ""]
    if before:
        r += [f"**{dur(tot['b_wall'])}**", f"**{dur(tot['b_work'])}**"]
    rows.append(r)
    out += ["### Summary", "", table(head, rows), ""]

    # Admits by goal type
    rows, tot = [], Counter()
    for j in sel:
        c = Counter(goal_type(a.get("claim")) for a in admits_of(j))
        tot.update(c)
        inv = c["invariant conjunct"]
        admitted = cases(j)[2]
        inv_cell = f"{inv} ({admitted} of them cases of split parts)" if admitted else blank0(inv)
        cells = [blank0(c[t]) if t != "invariant conjunct" else inv_cell for t in GOAL_TYPES]
        b = old(j)
        rows.append([j["title"], *cells, f"**{sum(c.values())}**" + (f" ({len(admits_of(b))})" if b else "")])
    rows.append(["**Total**", *[f"**{tot[t]}**" for t in GOAL_TYPES], f"**{sum(tot.values())}**"])
    out += ["### Admits by goal type", "",
            "`equal-output` is the record claim `equal-output+invariant`; an invariant conjunct is a claim "
            "`invariant/<predicate>`" + (" (a conjunct of `side_inv_<C>`)" if side else "") + ".", "",
            table([label, *GOAL_TYPES, "Total" + (" (before)" if before else "")], rows), ""]
    reasons = Counter(a["reason"] for j in sel for a in admits_of(j))
    out += ["Admit reasons: " + (", ".join(f"`{k}` {v}" for k, v in reasons.most_common()) or "none") + ".", ""]

    # Admits per oracle
    names = []
    for j in sel:
        names += [o for o in j["oracles"] if o not in names]
    rows = []
    for j in sel:
        b = old(j)
        cells = []
        for o in names:
            n = len(j["admits"].get(o, []))
            bn = len(b["admits"].get(o, [])) if b else 0
            cells.append("" if n == bn == 0 else with_before(n, bn if b else None))
        if any(cells):
            rows.append([j["title"], *cells])
    out += ["### Admits per oracle" + (", now (before)" if before else ""), "",
            "Only rows with an admit.", "", table([label, *names], rows) if rows else "No admit.", ""]

    # Invariant conjuncts by predicate
    rows = []
    for j in sel:
        c, k = Counter(), Counter()
        for a in admits_of(j):
            if goal_type(a.get("claim")) == "invariant conjunct":
                p = predicate(a["claim"])
                c[p] += 1
                k[p] += "(case " in a["claim"]
        b = old(j)
        bc = Counter(predicate(a["claim"]) for a in admits_of(b)
                     if goal_type(a.get("claim")) == "invariant conjunct") if b else Counter()
        if c or bc:
            cell = ", ".join(f"`{p}` {n}" + (f" ({k[p]} cases)" if k[p] else "") for p, n in c.most_common()) or "—"
            if b:
                cell += " (before: " + (", ".join(f"`{p}` {n}" for p, n in bc.most_common()) or "—") + ")"
            rows.append([j["title"], cell])
    out += ["### " + ("Game invariants" if side else "Invariant conjuncts") + " admitted", "",
            table([label, "Predicates (count)"], rows) if rows else "None.", ""]

    # Key case split
    rows = []
    for j in sel:
        parts, all_cases, admitted, with_admit = cases(j)
        if parts:
            rows.append([j["title"], parts, all_cases, all_cases - admitted, admitted,
                         parts - with_admit, with_admit])
    if rows:
        out += ["### Key case split", "",
                "A split part is a part on which `case (…) => [->|?].` is sent; a split on k key pairs has "
                "k + 1 cases. A case that does not close is admitted alone (`(case …)` in its claim). "
                "Counted from the `.ec` files.", "",
                table([label, "Split parts", "Cases", "Cases closed", "Cases admitted",
                       "Parts closed", "Parts with an admitted case"], rows), ""]

    # Where the time goes
    rows = []
    for j in sel:
        calls = [sum(o.get("calls", (0, 0, 0))[i] for o in j["oracles"].values()) for i in range(3)]
        rows.append([j["title"], dur(j["wall"]), dur(work(j)), dur(total(j, "lockstep")),
                     dur(total(j, "ec")), dur(total(j, "tactic")),
                     " / ".join(dur(total(j, k)) for k in ("translate", "prepare", "prover")),
                     dur(total(j, "serialize")), dur(total(j, "parse"), short=True),
                     " / ".join(map(num, calls))])
    out += ["### Where the time goes", "",
            "Work is Σ over oracles of lockstep + EasyCrypt time. EasyCrypt is Σ of the round trips; "
            "tactic is EasyCrypt executing the sentences, smt included.", "",
            table([label, "Wall", "Work", "Lockstep", "EasyCrypt", "→ tactic",
                   "(smt: translate / prepare / prover)", "→ serialize", "Domino parse",
                   "smt calls: valid / timeout / unknown"], rows), ""]

    # EasyCrypt time by role
    rows = []
    for j in sel:
        cells = []
        for role in ROLES:
            c = [o["roles"].get(role, (0, 0.0, 0)) for o in j["oracles"].values()]
            n, s, f = sum(x[0] for x in c), sum(x[1] for x in c), sum(x[2] for x in c)
            cells.append("—" if n == 0 else f"{num(n)} / {dur(s, short=True)}" + (f" / {num(f)}" if f else ""))
        rows.append([j["title"], *cells])
    out += ["### EasyCrypt time by role (Σ oracles; count / time / failed)", "",
            table([label, *ROLES], rows), ""]
    return out


def report(directory, before_ref):
    jobs = load(Tree(directory))
    before = load(Tree(directory, before_ref)) if before_ref else None
    theorem = os.path.basename(os.path.normpath(directory))
    updated = max(filter(None, (j["updated"] for j in jobs.values())), default="—")
    out = [f"# {theorem}: proof statistics per hop and side invariant", "",
           f"Generated by `scripts/proof_statistics.py` on "
           f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')} UTC from `session/*/*.record.json`, "
           f"`progress/*/report.txt` and the `.ec` files of `{directory}`. The latest session record is "
           f"of {updated}." + (f" \"Before\" is commit `{before_ref}`." if before_ref else ""), "",
           "Updated (session record) per job: " +
           ", ".join(f"{j['title']} {(j['updated'] or '—')[:10]}" for j in jobs.values()) + ".", ""]
    hops, sides = section(jobs, before, False), section(jobs, before, True)
    if hops:
        out += ["## Hops", ""] + hops
    if sides:
        out += ["## Side invariants", ""] + sides
    return "\n".join(out).rstrip() + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("directory", help="the <out>/<Theorem> directory of `domino easycrypt prove`")
    p.add_argument("--before", metavar="REF", help="git commit to compare with")
    p.add_argument("-o", "--output", help="write to FILE (default: stdout)")
    a = p.parse_args()
    if not os.path.isdir(os.path.join(a.directory, "progress")):
        p.error(f"{a.directory} has no progress/ directory: give the <out>/<Theorem> directory")
    text = report(a.directory, a.before)
    if a.output:
        with open(a.output, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
